#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITE } from './site.config.mjs';
import { PAGES } from './src/pages.mjs';
import { makeCtx, renderPage } from './src/layout.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const assetSrc = join(here, 'src/assets');
const assetHash = createHash('sha1');
for (const name of readdirSync(assetSrc).filter((n) => /\.(css|js)$/.test(n)).sort()) {
  assetHash.update(name).update(readFileSync(join(assetSrc, name), 'utf8').replace(/\r\n/g, '\n'));
}
assetHash.update('\0leadEndpoint\0').update(String(SITE.leadEndpoint || ''));
SITE.assetVersion = `${SITE.assetVersion}-${assetHash.digest('hex').slice(0, 8)}`;

const dev = process.argv.includes('--dev');
const outArg = process.argv.indexOf('--out');
const OUT = resolve(outArg > -1 ? process.argv[outArg + 1] : join(here, dev ? 'dev-build' : 'docs'));
const docsPath = resolve(here, 'docs');
if (dev && OUT === docsPath) {
  console.error('Refusing to write docs/ from a dev build.');
  process.exit(1);
}

function copyDir(from, to) {
  if (!existsSync(from)) return;
  mkdirSync(to, { recursive: true });
  for (const name of readdirSync(from)) {
    if (name.startsWith('.')) continue;
    const src = join(from, name);
    const dest = join(to, name);
    if (statSync(src).isDirectory()) copyDir(src, dest);
    else copyFileSync(src, dest);
  }
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
copyDir(assetSrc, join(OUT, 'assets'));

const browserConfig = {
  dev,
  leadEndpoint: SITE.leadEndpoint || '',
  phoneE164: SITE.phone.e164,
  phoneDisplay: SITE.phone.display,
  bookingUrl: SITE.bookingUrl,
  name: SITE.shortName,
  assetVersion: SITE.assetVersion,
};
writeFileSync(join(OUT, 'assets/config.js'), `/* Generated by build.mjs from site.config.mjs. */\nwindow.FGAI_CONFIG = ${JSON.stringify(browserConfig)};\n`);

const sitemap = [];
for (const page of PAGES) {
  const ctx = makeCtx(SITE, page.linkSlug ?? page.slug, { depth: page.depth, dev });
  const html = renderPage(ctx, page);
  const rel = page.file || (page.slug ? `${page.slug}/index.html` : 'index.html');
  mkdirSync(dirname(join(OUT, rel)), { recursive: true });
  writeFileSync(join(OUT, rel), html);
  if (page.inSitemap !== false) sitemap.push(page.slug ? ctx.abs(`${page.slug}/`) : ctx.abs(''));
}

const base = SITE.url.replace(/\/$/, '');
writeFileSync(join(OUT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemap.map((loc) => `  <url><loc>${loc}</loc><lastmod>${SITE.updated}</lastmod></url>`).join('\n')}
</urlset>
`);
writeFileSync(join(OUT, 'robots.txt'), SITE.launched
  ? `User-agent: *\nAllow: /\n\nSitemap: ${base}/sitemap.xml\n`
  : 'User-agent: *\nDisallow: /\n');
writeFileSync(join(OUT, '.nojekyll'), '');
if (SITE.customDomain) writeFileSync(join(OUT, 'CNAME'), `${SITE.customDomain}\n`);
console.log(`Built ${PAGES.length} pages into ${OUT} (${dev ? 'DEV' : 'production'}, ${SITE.launched ? 'launched' : 'not launched'}).`);
